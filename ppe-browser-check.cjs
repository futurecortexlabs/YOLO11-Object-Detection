const { chromium } = require('C:/Users/futur/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const page = await browser.newPage({viewport: {width:1440,height:1050},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:7862',{waitUntil:'networkidle'});
  await page.screenshot({path:'docs/ppe-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'この画像をAI解析',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('textarea[aria-label="解析ステータス"]')?.value.includes('未入力') || [...document.querySelectorAll('textarea')].some(x=>x.value.includes('画像が未入力')));
  await page.getByRole('button',{name:'サンプルで体験 →',exact:true}).click();
  const status = page.getByRole('textbox',{name:'解析ステータス',exact:true});
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.includes('シミュレーション')));
  assert.match(await status.inputValue(),/作業者 3人・要確認 2人/);
  assert.equal(await page.locator('a[href*="ppe-report-"]').count(),1);
  await page.screenshot({path:'docs/ppe-result.png',fullPage:true});
  await page.getByRole('checkbox',{name:'ヘルメット',exact:true}).uncheck();
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.includes('変更されました')));
  assert.equal(await page.locator('a[href*="ppe-report-"]').count(),0);
  await page.getByRole('button',{name:'サンプルで体験 →',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.includes('作業者 3人・要確認 1人')));
  await page.locator('input[type=file]').first().setInputFiles('models/ppe/sample_image.jpg');
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.includes('変更されました')));
  await page.getByRole('button',{name:'この画像をAI解析',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.startsWith('AI解析 /')),{},{timeout:60000});
  console.log('AI:',await status.inputValue());
  await page.getByRole('button',{name:'結果をリセット',exact:true}).click();
  await page.waitForFunction(()=>![...document.querySelectorAll('a')].some(x=>x.href.includes('ppe-report-')));
  await page.getByRole('tab',{name:'導入プランを整理',exact:true}).click();
  await page.getByRole('textbox',{name:'解決したい課題',exact:true}).fill('工場入口での装備確認を効率化したい');
  await page.getByRole('button',{name:'相談メモを作成',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.startsWith('PPE検出システム 開発相談')));
  assert.match(await page.locator('textarea').evaluateAll(nodes => nodes.find(x => x.value.startsWith('PPE検出システム 開発相談')).value),/工場入口/);
  await page.getByRole('tab',{name:'PPEモニター',exact:true}).click();
  await page.getByRole('button',{name:'サンプルで体験 →',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('textarea')].some(x=>x.value.includes('シミュレーション')));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/ppe-mobile.png',fullPage:true});
  const width=await page.evaluate(()=>({screen:innerWidth,content:document.documentElement.scrollWidth}));
  assert.ok(width.content<=width.screen,JSON.stringify(width));
  assert.deepEqual(errors,[]);
  console.log('PASS: empty input, simulation, settings invalidation, real inference, exports, reset, brief, mobile width, browser errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
